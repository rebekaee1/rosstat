export function getInternationalReservesChartTitle(chartMode) {
  switch (chartMode) {
    case 'monthly':
      return 'Международные резервы — среднее по месяцам (млрд $)';
    case 'quarterly':
      return 'Международные резервы — среднее по кварталам (млрд $)';
    case 'annual':
      return 'Международные резервы — среднее по годам (млрд $)';
    default:
      return 'Международные резервы — еженедельно (млрд $)';
  }
}

export function getInternationalReservesTableTitle(chartMode) {
  switch (chartMode) {
    case 'monthly':
      return 'Исторические данные — резервы, среднее по месяцам';
    case 'quarterly':
      return 'Исторические данные — резервы, среднее по кварталам';
    case 'annual':
      return 'Исторические данные — резервы, среднее по годам';
    default:
      return 'Исторические данные — международные резервы (еженедельно)';
  }
}

export function getInternationalReservesViewModeContent({ chartMode = 'level' }) {
  switch (chartMode) {
    case 'monthly':
      return contentAggMonthly();
    case 'quarterly':
      return contentAggQuarterly();
    case 'annual':
      return contentAggAnnual();
    default:
      return contentLevel();
  }
}

