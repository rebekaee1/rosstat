const SLICE = {
  'gdp-consumption': CONSUMPTION,
  'gdp-government': GOVERNMENT,
};

function sliceFor(code) {
  return SLICE[code] ?? CONSUMPTION;
}

export function getGdpUseChartTitle(chartMode, indicatorCode) {
  const s = sliceFor(indicatorCode);
  return chartMode === 'annual' ? s.chartAnnual : s.chartLevel;
}

export function getGdpUseTableTitle(chartMode, indicatorCode) {
  const s = sliceFor(indicatorCode);
  return chartMode === 'annual' ? s.tableAnnual : s.tableLevel;
}

export function getGdpUseViewModeContent({ chartMode = 'level', indicatorCode }) {
  const s = sliceFor(indicatorCode);
  return chartMode === 'annual' ? s.annual : s.level;
}

