export function getGdpRealChartTitle(chartMode) {
  switch (chartMode) {
    case 'yoy':
      return 'Реальный ВВП — год к году (%)';
    case 'qoq':
      return 'Реальный ВВП — квартал к кварталу (%)';
    case 'annual':
      return 'Реальный ВВП — сумма за год (млрд руб.)';
    default:
      return 'Реальный ВВП — поквартально (млрд руб.)';
  }
}

export function getGdpRealTableTitle(chartMode) {
  switch (chartMode) {
    case 'yoy':
      return 'Исторические данные — реальный ВВП, год к году';
    case 'qoq':
      return 'Исторические данные — реальный ВВП, кв/кв';
    case 'annual':
      return 'Исторические данные — реальный ВВП за год';
    default:
      return 'Исторические данные — реальный ВВП (поквартально)';
  }
}

export function getGdpRealViewModeContent({ chartMode = 'level' }) {
  switch (chartMode) {
    case 'yoy':
      return contentYoy();
    case 'qoq':
      return contentQoq();
    case 'annual':
      return contentAnnual();
    default:
      return contentLevel();
  }
}

