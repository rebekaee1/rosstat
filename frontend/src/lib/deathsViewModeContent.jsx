import { isDeathsDemoFamily } from './deathsViewModeResolve';

function contentDeathsLevel() {
  return {
    description:
      'На графике — число умерших за календарный год в тысячах человек '
      + 'по данным Росстата. Каждая точка — итог года, а не помесячный срез. '
      + 'Ряд отражает абсолютный масштаб смертности; для сравнения с учётом '
      + 'численности населения откройте срез «На 1000 населения» в переключателе '
      + 'среза. История на Forecast Economy — с 1990 года.',
    methodology:
      'Режим «за год» — исходный годовой ряд числа смертей в тыс. чел. '
      + 'Прогноз на карточке не строится. Для темпа изменения к прошлому году '
      + 'в процентах выберите «Год к году».',
  };
}

function contentDeathsYoy() {
  return {
    description:
      'На графике — изменение числа смертей к предыдущему календарному году '
      + 'в процентах. Положительное значение — рост абсолютного числа умерших; '
      + 'отрицательное — снижение. Это темп, а не уровень в тыс. чел. '
      + 'Сопоставляйте с коэффициентом смертности (‰) на соседнем срезе, '
      + 'если важна нормировка на население.',
    methodology:
      'Режим «год к году» — расчёт на Forecast Economy из годового ряда числа '
      + 'смертей: отношение к предыдущему году, в процентах. Единица — проценты, '
      + 'не тыс. чел. Отдельной публикации Росстата именно для этого ряда нет — '
      + 'удобное представление для анализа динамики.',
  };
}

function contentDeathRateLevel() {
  return {
    description:
      'На графике — коэффициент смертности: число умерших на 1000 человек '
      + 'населения за год по данным Росстата. Единица — промille (‰). '
      + 'Показатель учитывает размер населения, в отличие от абсолютного числа '
      + 'смертей. История на Forecast Economy — с 1990 года.',
    methodology:
      'Режим «за год» — исходный годовой ряд коэффициента смертности. '
      + 'Прогноз не строится. Абсолютное число смертей — срез «Число смертей» '
      + 'в переключателе среза. Темп к прошлому году — режим «Год к году».',
  };
}

function contentDeathRateYoy() {
  return {
    description:
      'На графике — изменение коэффициента смертности к предыдущему '
      + 'календарному году в процентах. Отражает ускорение или замедление '
      + 'смертности с учётом численности населения. Не путать с уровнем в ‰ '
      + 'и с абсолютным числом смертей в тыс. чел.',
    methodology:
      'Режим «год к году» — расчёт из годового ряда коэффициента смертности: '
      + 'отношение к предыдущему году, в процентах. Это производное представление '
      + 'на сайте, а не отдельная строка ежегодного бюллетеня Росстата.',
  };
}

export function getDeathsChartTitle(chartMode, indicatorCode = 'deaths') {
  const isRate = indicatorCode === 'death-rate';
  if (chartMode === 'yoy') {
    return isRate
      ? 'Коэффициент смертности — год к году (%)'
      : 'Число смертей — год к году (%)';
  }
  return isRate
    ? 'Коэффициент смертности — за год (‰)'
    : 'Число смертей — за год (тыс. чел.)';
}

export function getDeathsTableTitle(chartMode, indicatorCode = 'deaths') {
  const isRate = indicatorCode === 'death-rate';
  if (chartMode === 'yoy') {
    return isRate
      ? 'Исторические данные — коэффициент смертности, г/г'
      : 'Исторические данные — число смертей, г/г';
  }
  return isRate
    ? 'Исторические данные — коэффициент смертности'
    : 'Исторические данные — число смертей';
}

export function getDeathsViewModeContent({ chartMode = 'level', indicatorCode = 'deaths' }) {
  const isRate = indicatorCode === 'death-rate';
  if (chartMode === 'yoy') {
    return isRate ? contentDeathRateYoy() : contentDeathsYoy();
  }
  return isRate ? contentDeathRateLevel() : contentDeathsLevel();
}

export { isDeathsDemoFamily };
