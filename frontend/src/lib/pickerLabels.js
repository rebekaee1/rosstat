/**
 * Подписи переключателей показа (режим, частота) для человека.
 *
 * Конфиги семей и legacy-группы отдают «канцелярские» подписи («К соотв. периоду пред. года», «Г/г»,
 * «нет официального ряда»). Источник правды они не меняют (на них завязаны URL, тесты и английский словарь),
 * поэтому раскрываем сокращения на выходе: тут, а не в данных. EN идёт через прежний словарь.
 */
import { localizeViewModeLabel } from '../i18n/viewModeLabels';

const RU_EXACT = {
  'К соотв. периоду пред. года': 'Год к году',
  'К году': 'Год к году',
  'Г/г': 'Год к году',
  'Кв/Кв': 'Квартал к кварталу',
  'Кв/кв': 'Квартал к кварталу',
  'М/м': 'Месяц к месяцу',
  'Н/н': 'Неделя к неделе',
  'Д/д': 'День ко дню',
  'К прошлому периоду': 'К прошлому значению',
  'К прошлому периоду (м/м)': 'К прошлому значению (месяц к месяцу)',
  'К прошлому периоду (кв/кв)': 'К прошлому значению (квартал к кварталу)',
  'К прошлому периоду (г/г)': 'К прошлому значению (год к году)',
  'На конец периода': 'На конец',
  'Средняя за период': 'В среднем',
  'За период': 'Итого',
  'Скользящее 12 мес.': 'Скользящее за 12 месяцев',
  '12М среднее': 'Среднее за 12 месяцев',
  'нет официального ряда': 'нет официальных данных',
  'расчётный ряд': 'расчёт по данным ведомства',
};

const RU_PREFIX = [
  ['К соотв. периоду пред. года', 'Год к году'],
];

/** Подпись на нужном языке; для RU — с раскрытыми сокращениями. */
export function pickerLabel(label, locale) {
  if (label == null || label === '') return label;
  if (locale === 'en') return localizeViewModeLabel(label, locale);
  const text = String(label);
  if (RU_EXACT[text]) return RU_EXACT[text];
  for (const [from, to] of RU_PREFIX) {
    if (text.startsWith(from)) return `${to}${text.slice(from.length)}`;
  }
  return text
    .replace(/соотв\.\s+периоду\s+пред\.\s+года/gi, 'тому же периоду прошлого года')
    .replace(/пред\.\s+года/gi, 'прошлого года')
    .replace(/пред\.\s+периоду/gi, 'прошлому значению')
    .replace(/К прошлому периоду/g, 'К прошлому значению');
}

/** Ключ i18n одной строки-подсказки под выбранным режимом (по исходной подписи) или null. */
const HINT_KEYS = {
  'На конец периода': 'w3.hint.periodEnd',
  'Средняя за период': 'w3.hint.periodAvg',
  'К прошлому периоду': 'w3.hint.vsPrevious',
  'К соотв. периоду пред. года': 'w3.hint.yoy',
  'К году': 'w3.hint.yoy',
  'Г/г': 'w3.hint.yoy',
  'Год к году': 'w3.hint.yoy',
};

export function pickerHintKey(rawLabel) {
  return HINT_KEYS[rawLabel] || null;
}
