function contentIndex(safeViewMode) {
  if (safeViewMode === 'index-quarterly') {
    return {
      description:
        'Уровень цен производителей на конец каждого квартала относительно '
        + 'опорного 2010 года (2010 = 100). Режим укрупняет помесячный ряд '
        + 'до квартальной частоты: показывается значение последнего месяца квартала.',
      methodology:
        'Накопленный индекс цен производителей промышленных товаров, база '
        + '2010 = 100. Для квартального представления берётся уровень индекса '
        + 'на конец квартала. Источник — Росстат.',
    };
  }
  if (safeViewMode === 'index-annual') {
    return {
      description:
        'Уровень цен производителей на конец каждого года относительно '
        + 'опорного 2010 года (2010 = 100). Режим показывает значение '
        + 'декабря каждого года и удобен для сравнения долгосрочной динамики.',
      methodology:
        'Накопленный индекс цен производителей промышленных товаров, база '
        + '2010 = 100. Для годового представления берётся уровень индекса '
        + 'на конец года (декабрь). Источник — Росстат.',
    };
  }
  return {
    description:
      'Накопленный индекс цен производителей промышленных товаров '
      + '(2010 = 100): уровень оптовых цен относительно опорного года. '
      + 'Линия показывает не темп, а сам уровень цен, который растёт по мере '
      + 'накопления месячной инфляции.',
    methodology:
      'Ежемесячный уровень цен производителей в системе 2010 = 100. '
      + 'Индекс строится по выборке предприятий и видов продукции; месячные '
      + 'приросты последовательно наращивают уровень. Источник — Росстат.',
  };
}

export function getPpiViewModeContent({ chartMode, safeViewMode, indicator }) {
  if (chartMode === 'yoy') return contentYoy();
  if (chartMode === 'mom') return contentMom();
  if (chartMode === 'index') return contentIndex(safeViewMode);
  return {
    description: indicator?.description ?? '',
    methodology: indicator?.methodology ?? '',
  };
}
