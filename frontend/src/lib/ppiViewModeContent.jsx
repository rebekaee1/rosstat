/**
 * Описание и методология: режимы ИЦП («под копирку» с ИПЦ, созвон 2026-06-11).
 * Правила: .cursor/rules/methodology-language.mdc
 */

function indexPeriodSuffix(safeViewMode) {
  if (safeViewMode === 'index-quarterly') return ' на конец квартала';
  if (safeViewMode === 'index-annual') return ' на конец года';
  return '';
}

function yoyPeriodSuffix(safeViewMode) {
  if (safeViewMode === 'yoy-quarter') return ' (по кварталам)';
  if (safeViewMode === 'yoy-year') return ' (по годам)';
  return '';
}

export function getPpiChartTitle(chartMode, safeViewMode) {
  switch (chartMode) {
    case 'yoy':
      return `Инфляция к соответствующему периоду предыдущего года — цены производителей (%)${yoyPeriodSuffix(safeViewMode)}`;
    case 'mom':
      return 'К прошлому месяцу — индекс цен производителей (%)';
    case 'qoq':
      return 'К прошлому кварталу — индекс цен производителей (%)';
    case 'annual':
      return 'Годовое изменение (г/г) — цены производителей (%)';
    case 'index':
      return `Индекс цен производителей (2010 = 100)${indexPeriodSuffix(safeViewMode)}`;
    default:
      return 'Динамика индекса цен производителей';
  }
}

export function getPpiTableTitle(chartMode, safeViewMode) {
  switch (chartMode) {
    case 'yoy':
      return `Исторические данные — инфляция к соотв. периоду предыдущего года (%)${yoyPeriodSuffix(safeViewMode)}`;
    case 'mom':
      return 'Исторические данные — к прошлому месяцу (%)';
    case 'qoq':
      return 'Исторические данные — к прошлому кварталу (%)';
    case 'annual':
      return 'Исторические данные — годовое изменение г/г (%)';
    case 'index': {
      if (safeViewMode === 'index-quarterly') return 'Исторические данные — индекс на конец квартала';
      if (safeViewMode === 'index-annual') return 'Исторические данные — индекс на конец года';
      return 'Исторические данные — индекс (2010 = 100)';
    }
    default:
      return 'Исторические данные — ИЦП';
  }
}

