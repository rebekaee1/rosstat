export function getGdpNominalChartTitle(chartMode) {
  switch (chartMode) {
    case 'yoy':
      return 'Номинальный ВВП — год к году (%)';
    case 'qoq':
      return 'Номинальный ВВП — квартал к кварталу (%)';
    case 'annual':
      return 'Номинальный ВВП — сумма за год (млрд руб.)';
    default:
      return 'Номинальный ВВП — поквартально (млрд руб.)';
  }
}

export function getGdpNominalTableTitle(chartMode) {
  switch (chartMode) {
    case 'yoy':
      return 'Исторические данные — номинальный ВВП, год к году';
    case 'qoq':
      return 'Исторические данные — номинальный ВВП, кв/кв';
    case 'annual':
      return 'Исторические данные — номинальный ВВП за год';
    default:
      return 'Исторические данные — номинальный ВВП (поквартально)';
  }
}

export function getGdpNominalViewModeContent({ chartMode = 'level' }) {
  switch (chartMode) {
    case 'yoy':
      return contentYoy();
    case 'qoq':
      return contentQoq();
    case 'annual':
      return contentAnnual();
    default:
      return contentLevel();
  }
}

