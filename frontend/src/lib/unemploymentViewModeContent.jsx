function contentQuarterly() {
  return {
    description:
      'На графике — среднее помесячное значение уровня безработицы внутри '
      + 'каждого календарного квартала (в %). Три месяца квартала усредняются: '
      + 'так видно, был ли квартал в целом «жёстче» по рынку труда, даже если '
      + 'один месяц выбился из ряда. Это не годовая безработица и не прирост '
      + 'к прошлому кварталу — только усреднённый уровень в процентах.',
    methodology:
      'Режим «по кварталам» — производный ряд: простое среднее трёх помесячных '
      + 'оценок Росстата внутри квартала. Отдельной публикации «безработица за '
      + 'квартал» у Росстата нет — расчёт выполняется при отображении из '
      + 'официального помесячного ряда. Частота точек — квартальная. '
      + 'Сравнивайте с помесячным режимом, если нужна детализация внутри года.',
  };
}

function contentAnnual() {
  return {
    description:
      'На графике — скользящее среднее уровня безработицы за последние '
      + '12 месяцев (в %). Каждая точка — среднее значение за годовое окно, '
      + 'заканчивающееся в данном месяце: тренд читается мягче, чем по '
      + 'отдельным месяцам. Это не среднее внутри календарного года и не '
      + 'годовой максимум безработицы — именно 12-месячное сглаживание уровня.',
    methodology:
      'Режим «12М среднее» — производный ряд: для каждого месяца считается '
      + 'среднее помесячных уровней за предыдущие 12 месяцев включая текущий. '
      + 'Ряд остаётся с помесячной сеткой дат, но значения менее шумные. '
      + 'Не путать с режимом «по кварталам» и с годовым приростом в пунктах — '
      + 'на графике по-прежнему уровень безработицы в процентах.',
  };
}

export function getUnemploymentChartTitle(chartMode) {
  switch (chartMode) {
    case 'quarterly':
      return 'Уровень безработицы — среднее по кварталам (%)';
    case 'annual':
      return 'Уровень безработицы — 12М среднее (%)';
    default:
      return 'Уровень безработицы — помесячно (%)';
  }
}

export function getUnemploymentTableTitle(chartMode) {
  switch (chartMode) {
    case 'quarterly':
      return 'Исторические данные — безработица, среднее по кварталам';
    case 'annual':
      return 'Исторические данные — безработица, 12М среднее';
    default:
      return 'Исторические данные — безработица (помесячно)';
  }
}

export function getUnemploymentViewModeContent({ chartMode = 'level' }) {
  if (chartMode === 'quarterly') return contentQuarterly();
  if (chartMode === 'annual') return contentAnnual();
  return contentLevel();
}

export { isUnemploymentFamily };
