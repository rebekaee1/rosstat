      'Режим «помесячно» — исходный ежемесячный ряд уровня безработицы '
      + '(история на Forecast Economy с 1990-х годов). Значение — доля '
      + 'безработных в рабочей силе в процентах на месяц. Прогноз на карточке '
      + 'может быть доступен для этого режима — см. переключатель «Прогноз». '
      + 'Для сглаживания откройте «Сглаживание»: квартальное среднее или '
