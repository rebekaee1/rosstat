export function getBankCreditChartTitle(chartMode) {
  switch (chartMode) {
    case 'quarterly':
      return 'Кредиты бизнесу — среднее по кварталам (трлн руб.)';
    case 'annual':
      return 'Кредиты бизнесу — среднее по годам (трлн руб.)';
    default:
      return 'Кредиты бизнесу — портфель (трлн руб.)';
  }
}

export function getBankCreditTableTitle(chartMode) {
  switch (chartMode) {
    case 'quarterly':
      return 'Исторические данные — кредиты компаниям, среднее по кварталам';
    case 'annual':
      return 'Исторические данные — кредиты компаниям, среднее по годам';
    default:
      return 'Исторические данные — кредиты компаниям (помесячно)';
  }
}

export function getBankCreditViewModeContent({ chartMode = 'level' }) {
  if (chartMode === 'quarterly') return contentAggQuarterly();
  if (chartMode === 'annual') return contentAggAnnual();
  return contentLevel();
}

