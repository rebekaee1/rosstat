import { isExternalDebtFamily } from './externalDebtViewModeResolve';

function contentLevel() {
  return {
    description:
      'На графике — совокупный внешний долг Российской Федерации в млн долларов '
      + 'США на конец каждого квартала: официальная оценка Банка России. '
      + 'Каждая точка относится к одному календарному кварталу; рост линии '
      + 'означает увеличение обязательств резидентов перед нерезидентами в '
      + 'валютном выражении, снижение — погашения и переоценки, а не '
      + 'обязательное «обнуление» долга за три месяца.',
    methodology:
      'Режим «поквартально» — исходный квартальный ряд Банка России без '
      + 'пересчёта в годовые средние. Значение — остаток внешних обязательств '
      + 'на дату публикации, а не новые заимствования за квартал и не процент '
      + 'по обслуживанию. Прогноз не строится. Чтобы сравнить годы без '
      + 'доминирования одного сильного квартала, выберите «Среднее за период — '
      + 'по годам».',
  };
}

function contentAggAnnual() {
  return {
    description:
      'На графике — средний квартальный уровень внешнего долга внутри '
      + 'каждого календарного года (млн долларов США). Годовая точка '
      + 'отвечает на вопрос, каким был «типичный» квартал по величине долга '
      + 'в этом году, а не только показатель на конец декабря.',
    methodology:
      'Режим «среднее за период — по годам»: простое среднее четырёх '
      + 'квартальных остатков внутри года из того же официального ряда. '
      + 'Отдельной годовой публикации «средний внешний долг» у регулятора '
      + 'нет — расчёт на стороне отображения. Удобно сопоставить эпохи '
      + 'роста и снижения долговой нагрузки, когда внутри года один квартал '
      + 'выбился из тренда. Не путать с суммой заимствований за год.',
  };
}

export function getExternalDebtChartTitle(chartMode) {
  switch (chartMode) {
    case 'annual':
      return 'Внешний долг — среднее по годам (млн $)';
    default:
      return 'Внешний долг — поквартально (млн $)';
  }
}

export function getExternalDebtTableTitle(chartMode) {
  switch (chartMode) {
    case 'annual':
      return 'Исторические данные — внешний долг, среднее по годам';
    default:
      return 'Исторические данные — внешний долг (поквартально)';
  }
}

export function getExternalDebtViewModeContent({ chartMode = 'level' }) {
  if (chartMode === 'annual') return contentAggAnnual();
  return contentLevel();
}

export { isExternalDebtFamily };
