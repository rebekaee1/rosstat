/**
 * Описание и методология: ключевая ставка ЦБ (режим × частота ряда).
 * Правила: .cursor/rules/methodology-language.mdc
 */

import { isKeyRateFamily } from './keyRateViewModeResolve';

function contentLevel() {
  return {
    description:
      'На графике — официальный уровень ключевой ставки в процентах годовых '
      + 'на каждую дату её изменения: ступенчатая линия отражает решения '
      + 'совета директоров Банка России. До сентября 2013 года в том же ряду '
      + 'исторически показана ставка рефинансирования как прежний ориентир '
      + 'политики. Это уровень инструмента, а не прирост за день или за год.',
    methodology:
      'Режим «уровень ставки» — ежедневный (по датам изменения) официальный '
      + 'ряд Банка России. Каждая точка — действующая ставка с указанной даты; '
      + 'между заседаниями линия горизонтальна. Прогноз на этой карточке не '
      + 'строится: решение по ставке публикуется ЦБ отдельно. Для сглаженного '
      + 'вида без «лесенки» выберите группу «Среднее за период» в переключателе '
      + 'над графиком.',
  };
}

function contentAgg(mode) {
  const labels = {
    weekly: 'неделям',
    monthly: 'месяцам',
    quarterly: 'кварталам',
    annual: 'годам',
  };
  const period = labels[mode] ?? 'периодам';
  return {
    description:
      `На графике — среднее значение ключевой ставки внутри календарных `
      + `${period}: из ежедневного ряда считается простое среднее по всем `
      + `дням, когда действовала та или иная ставка внутри интервала. `
      + `Так удобнее сравнивать «типичный» уровень политики за месяц или `
      + `квартал без скачков внутри периода.`,
    methodology:
      `Режим «среднее за период — ${period === 'неделям' ? 'по неделям' : period === 'месяцам' ? 'по месяцам' : period === 'кварталам' ? 'по кварталам' : 'по годам'}»: `
      + 'агрегация выполняется на стороне отображения из того же официального '
      + 'ряда, что и в режиме уровня. Это не отдельная публикация ЦБ. '
      + 'Точка на графике — средневзвешенное по календарю среднее ставки '
      + 'за интервал; при нескольких изменениях ставки внутри месяца все '
      + 'дни учитываются с равным весом.',
  };
}

export function getKeyRateChartTitle(chartMode) {
  switch (chartMode) {
    case 'weekly':
      return 'Ключевая ставка — среднее по неделям (%)';
    case 'monthly':
      return 'Ключевая ставка — среднее по месяцам (%)';
    case 'quarterly':
      return 'Ключевая ставка — среднее по кварталам (%)';
    case 'annual':
      return 'Ключевая ставка — среднее по годам (%)';
    default:
      return 'Ключевая ставка ЦБ РФ (%)';
  }
}

export function getKeyRateTableTitle(chartMode) {
  switch (chartMode) {
    case 'weekly':
      return 'Исторические данные — среднее по неделям';
    case 'monthly':
      return 'Исторические данные — среднее по месяцам';
    case 'quarterly':
      return 'Исторические данные — среднее по кварталам';
    case 'annual':
      return 'Исторические данные — среднее по годам';
    default:
      return 'Исторические данные — ключевая ставка';
  }
}

export function getKeyRateViewModeContent({ chartMode = 'level' }) {
  if (chartMode === 'level') return contentLevel();
  if (['weekly', 'monthly', 'quarterly', 'annual'].includes(chartMode)) {
    return contentAgg(chartMode);
  }
  return contentLevel();
}

export { isKeyRateFamily };
