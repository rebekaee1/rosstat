export function getWagesNominalChartTitle(chartMode) {
  switch (chartMode) {
    case 'annual':
      return 'Средняя зарплата — годовой ряд (руб.)';
    case 'real':
      return 'Реальная заработная плата (%)';
    case 'yoy':
      return 'Средняя зарплата — год к году (%)';
    case 'index':
      return 'Индекс заработной платы (2015=100)';
    default:
      return 'Средняя зарплата — помесячно (руб.)';
  }
}

export function getWagesNominalTableTitle(chartMode) {
  switch (chartMode) {
    case 'annual':
      return 'Исторические данные — зарплата, годовой ряд';
    case 'real':
      return 'Исторические данные — реальная зарплата';
    case 'yoy':
      return 'Исторические данные — зарплата, год к году';
    case 'index':
      return 'Исторические данные — индекс зарплаты';
    default:
      return 'Исторические данные — номинальная зарплата (помесячно)';
  }
}

export function getWagesNominalViewModeContent({ chartMode = 'level' }) {
  switch (chartMode) {
    case 'annual':
      return contentAnnual();
    case 'real':
      return contentReal();
    case 'yoy':
      return contentYoy();
    case 'index':
      return contentIndex();
    default:
      return contentLevel();
  }
}

