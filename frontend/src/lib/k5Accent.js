/**
 * K5. Разбор названия для золотого слова-акцента: последнее слово (не короче 3 букв) отделяется от знаков в конце.
 * Одно слово и короткий хвост («в», «на», «ТВ») акцента не получают. Текст склеивается обратно без потерь.
 */
const SPLIT = /^([\s\S]*\s)([^\s)\]»"'.,;:!?]{3,})([)\]»"'.,;:!?]*)$/;

export function splitAccent(text) {
  const value = String(text ?? '');
  const m = SPLIT.exec(value);
  if (!m) return null;
  return { head: m[1], word: m[2], tail: m[3] };
}
