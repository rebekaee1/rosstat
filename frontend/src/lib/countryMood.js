function hue(hex) {
  const n = parseInt(hex.slice(1), 16);
  const r = ((n >> 16) & 255) / 255;
  const g = ((n >> 8) & 255) / 255;
  const b = (n & 255) / 255;
  const max = Math.max(r, g, b);
  const d = max - Math.min(r, g, b);
  if (d === 0) return -1;
  let h;
  if (max === r) h = ((g - b) / d) % 6;
  else if (max === g) h = (b - r) / d + 2;
  else h = (r - g) / d + 4;
  return ((h * 60) + 360) % 360;
}

/** Красные, розовые и жёлтые оттенки на светлой плите дают грязное тёплое пятно («слишком жёлтый», круг 6): они уходят в холодный синий бренда. */
const isReddish = (hex) => {
  const h = hue(hex);
  return h >= 0 && (h >= 335 || h <= 70);
};

/** Два чистых цвета для пятен за героем страны по ISO-коду; красное и жёлтое заменено холодным синим, неизвестный код даёт синий бренда. */
export function moodColors(code) {
  const pair = FLAG_COLORS[String(code || '').trim().toUpperCase()];
  if (!pair) return [...BRAND];
  const clean = pair.map((hex, i) => (isReddish(hex) ? BRAND[i] : hex));
  return clean;
}

export default moodColors;
