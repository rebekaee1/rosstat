// Когда смена адреса — новый просмотр страницы, а когда — запись состояния контрола в URL.
//
// Контролы страниц пишут своё состояние в адрес заменой записи истории
// (navigate/setSearchParams с { replace: true }): год на карте регионов,
// поля калькулятора, режим графика, фильтры рейтинга. Это тот же экран.
// До 19.11.2026 каждая такая запись считалась новым просмотром: собственный
// счётчик закрывал страницу (dwell 16–70 мс) и открывал новую, Метрика
// получала hit. Перетаскивание года давало десятки «просмотров» за секунду,
// и средняя длительность просмотра карты падала до 0,5 с у человека,
// который смотрел карту 16 минут (боевой, 16.09.2026, гипотезы Пульса 202/208).
//
// Правило: замена записи истории без смены пути — не новый просмотр.
// Переход ссылкой (PUSH), назад/вперёд (POP) и замена со сменой пути
// (редирект на канон, смена показателя карты) остаются просмотрами.

export function isSamePageUrlSync({ navigationType, prevPathname, nextPathname }) {
  return navigationType === 'REPLACE' && prevPathname === nextPathname;
}
