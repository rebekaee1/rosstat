export const SUB_ORDER = ['home', 'tech', 'care', 'clothes', 'shoes', 'kids', 'build', 'leisure', 'other'];

/** Подгруппа позиции «Одежда и товары» по названию. */
export function goodsSubgroup(item) {
  const text = String(item.short_name || item.name || '').toLowerCase();
  const hit = RULES.find(([, re]) => re.test(text));
  return hit ? hit[0] : 'other';
}

/** { key, items }[] в порядке SUB_ORDER, пустые подгруппы не нужны. */
export function splitGoods(items) {
  const map = new Map();
  items.forEach((it) => {
    const k = goodsSubgroup(it);
    if (!map.has(k)) map.set(k, []);
    map.get(k).push(it);
  });
  return SUB_ORDER.filter((k) => map.has(k)).map((k) => ({ key: k, items: map.get(k) }));
}

/** Ряд кнопок подгрупп: «Все 341, Дом 40, Техника 25 …». */
export function GoodsSubChips({ parts, total, value, onChange }) {
  const { t } = useLocale();
  return (
    <div className="z1p-chips r8b-subchips fe-chip-row" role="group" aria-label={t('r8b.sub.aria')} data-testid="goods-subchips">
      <button type="button" aria-pressed={!value} className={`fe-chip fe-press ${!value ? 'is-active' : ''}`} onClick={() => onChange('')}>
        {t('z1.prices.groupAll')}
        <span className="z1p-chips__n">{total}</span>
      </button>
      {parts.map((p) => (
        <button key={p.key} type="button" aria-pressed={value === p.key} className={`fe-chip fe-press ${value === p.key ? 'is-active' : ''}`} onClick={() => onChange(p.key)}>
          {t(`r8b.sub.${p.key}`)}
          <span className="z1p-chips__n">{p.items.length}</span>
        </button>
      ))}
    </div>
  );
}
