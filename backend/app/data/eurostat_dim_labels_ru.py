_AGE_RANGE_RE = re.compile(r"^Y(\d+)-(\d+)$", re.I)
_AGE_LT_RE = re.compile(r"^Y_LT(\d+)$", re.I)
_AGE_GE_RE = re.compile(r"^Y_GE(\d+)$", re.I)
_AGE_SINGLE_RE = re.compile(r"^Y(\d+)$", re.I)
_DAY_RANGE_RE = re.compile(r"^D(\d+)-(\d+)$", re.I)
_DAY_SINGLE_RE = re.compile(r"^D(\d+)$", re.I)


def _years_word(n: int) -> str:
    """Склонение «год/года/лет» для возраста."""
    n_abs = abs(n) % 100
    if 11 <= n_abs <= 14:
        return "лет"
    last = n_abs % 10
    if last == 1:
        return "год"
    if 2 <= last <= 4:
        return "года"
    return "лет"


def _days_word(n: int) -> str:
    n_abs = abs(n) % 100
    if 11 <= n_abs <= 14:
        return "дней"
    last = n_abs % 10
    if last == 1:
        return "день"
    if 2 <= last <= 4:
        return "дня"
    return "дней"


def _age_label_fallback(code: str) -> str | None:
    """Собрать русскую подпись возраста по шаблону кода Eurostat."""
    m = _AGE_RANGE_RE.match(code)
    if m:
        a, b = int(m.group(1)), int(m.group(2))
        # В диапазонах возраста по-русски устойчиво «лет».
        return f"{a}–{b} лет"

    m = _AGE_LT_RE.match(code)
    if m:
        n = int(m.group(1))
        return f"младше {n} {_years_word(n)}"

    m = _AGE_GE_RE.match(code)
    if m:
        n = int(m.group(1))
        return f"{n} {_years_word(n)} и старше"

    m = _AGE_SINGLE_RE.match(code)
    if m:
        n = int(m.group(1))
        return f"{n} {_years_word(n)}"

    m = _DAY_RANGE_RE.match(code)
    if m:
        a, b = int(m.group(1)), int(m.group(2))
        return f"{a}–{b} {_days_word(b)}"

    m = _DAY_SINGLE_RE.match(code)
    if m:
        n = int(m.group(1))
        if n == 0:
            return "младше 1 дня"
        return f"{n} {_days_word(n)}"

    return None


def label_for_dim_member(dim: str, code: str | None) -> str | None:
    """Русская подпись члена измерения или None, если неизвестен.

    dim нормализуется в lower, code — в upper.
    Для age при отсутствии явной записи пробуется шаблонный разбор.
    """
    if code is None:
        return None
    d = (dim or "").strip().lower()
    c = (code or "").strip().upper()
    if not d or not c:
        return None

    table = LABELS_BY_DIM.get(d)
    if table is not None:
        hit = table.get(c)
        if hit is not None:
            return hit

    if d == "age":
        return _age_label_fallback(c)

    return None


def is_dim_totalish(dim: str, code: str | None) -> bool:
    """True, если код — «итого» / не сужает смысл ряда для публичного имени."""
    d = (dim or "").strip().lower()
    c = (code or "").strip().upper()
    if c in _GLOBAL_TOTALISH:
        return True
    extra = _DIM_TOTALISH.get(d)
    if extra is not None and c in extra:
        return True
    return False
