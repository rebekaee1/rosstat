"""Исторический seed для среднемесячной номинальной заработной платы (1991-2014).

Источник:
- Росстат, статистический сборник «Россия в цифрах» (издания 2000-2020),
  раздел «Уровень жизни населения», таблица «Среднемесячная номинальная
  начисленная заработная плата работников по полному кругу организаций».
- Перекрёстная сверка: ЕМИСС (fedstat.ru, показатель 57826) +
  сборник «Социальное положение и уровень жизни населения России».

**Деноминация 1998**: 1 января 1998 г. → 1000 старых рублей = 1 новый рубль.
Все значения 1991-1997 здесь приведены к **новым** рублям (поделены на 1000),
чтобы временной ряд был непрерывен и сопоставим с современным
`wages-nominal` (с 2015) без визуального скачка.

В нынешних рублях, по итогу деноминации:
- 1991: 548 руб (старых) → 0.548 (новых)
- 1995: 472 392 руб (старых) → 472.4 (новых)
- 1997: 950 205 руб (старых) → 950.2 (новых)
- 1998: 1 051 руб (новых) — первый год новой шкалы.

Frequency = годовая (точка 1 января — стандарт Росстата для annual-публикаций).
В БД эти точки лягут как `frequency_label="annual_historical"` и не будут
конфликтовать с monthly-точками с 2015. Frontend chart показывает их как
часть единого ряда через `connectNulls=true` или явный downsample.

Часть проблемы — деноминация рублей нарушает экономический смысл «средняя
ЗП за 1991 = 0.548 руб». Это **исторический артефакт**, не баг. Frontend
формат-функция `formatNumber` обрабатывает диапазон [0, 200000] корректно.
"""

