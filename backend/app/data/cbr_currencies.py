def _stem(c: CbrCurrency) -> str:
    return c.nom.split()[0].casefold()[:5]


def search_concepts() -> tuple[tuple[tuple[str, ...], tuple[str, ...]], ...]:
    """Фразы запроса → ряд: «курс сума», «сум к рублю», «uzs rub» (search_intent.CONCEPTS)."""
    out = []
    for c in CBR_CURRENCIES:
        iso = c.iso.casefold()
        en = c.en.casefold()
        aliases = (
            f"курс {c.gen} к рублю", f"{c.gen} к рублю", f"{c.nom} к рублю", f"курс {c.gen}",
            c.nom.casefold(), c.gen.casefold(), f"{iso} rub", f"{iso}rub",
            f"{en} to ruble", f"{en} to rouble", en,
            *c.aliases,
            # «курс сума», «курс дирхама»: короткое имя с «курс» и «к рублю».
            *(f"курс {a}" for a in c.aliases if " " not in a),
            *(f"{a} к рублю" for a in c.aliases if " " not in a),
        )
        seen: list[str] = []
        for alias in aliases:
            alias = alias.casefold()
            if alias not in seen:
                seen.append(alias)
        out.append((tuple(seen), (c.code, f"{iso} rub", _stem(c))))
    return tuple(out)


def measure_rules() -> dict[str, tuple[tuple[str, ...], tuple[str, ...]]]:
    """Ряд обязан нести валюту и рубль в названии или коде (search_language.MEASURE_RULES)."""
    rules = {}
    for c in CBR_CURRENCIES:
        iso = c.iso.casefold()
        en_stem = c.en.split()[0].casefold()[:5]
        excluded = r"effective exchange|эффективн.*курс"
        if c.iso == "GBP":
            excluded += r"|египет|egypt"
        rules[c.code] = ((rf"\b{iso}\b|{_stem(c)}|{en_stem}", r"rub|ruble|rouble|руб"), (excluded,))
    return rules
