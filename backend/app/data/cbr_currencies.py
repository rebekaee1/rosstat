"""Официальные курсы Банка России: справочник всех валют ежедневной ведомости.

Одна точка истины для 49 рублёвых пар, добавленных 08.11.2026 (до этого на
сайте было пять: доллар, евро, юань, лира, тенге — они описаны в seed вручную и
здесь не повторяются). Из справочника собираются строки seed, generic-семьи,
SEO, английские тексты, пути раздела валют, поиск и выход со страницы страны.

Источник — ведомость ``XML_daily.asp`` и динамика ``XML_dynamic.asp`` Банка
России. Коды валют, номиналы, первая дата и дата, с которой курс
устанавливается ежедневно, сверены живыми запросами 08.11.2026 (ведомость на
07.11.2026, 54 валюты).

Единица котировки (``quote_units``). Ряды хранятся в ``Numeric(12, 4)``.
Когда за одну единицу валюты выходит меньше 10 копеек (иена, вона, сум, донг,
риал…), ряд хранится за 100, 1 000, 10 000 или 1 000 000 единиц — как в
ведомости Банка России. Это записано в единице ряда («руб. за 100»), и
конвертер раздела валют делит на неё. Парсер пересчитывает каждую запись по её
собственному номиналу: номинал у ЦБ со временем менялся.

Где история начинается позже 1998 года и почему:

* TJS — с 01.11.2000: раньше в динамике таджикский рубль (сомони введён в
  2000 году, 1 сомони = 1000 рублей), скачок в 900 раз;
* CUP и IRR — с 11.07.2025: в этот день Банк России сменил базу официального
  курса кубинского песо и иранского риала (скачок в 10 и 23 раза). Ряд показывает
  действующий режим; прежний остаётся в первоисточнике;
* AZN 2006, RON 2005, RSD 2007, TMT 2009, BYN 2016 — валюты после деноминации
  с новым кодом у ЦБ; MMK — котируется ЦБ с 11.07.2025.

До даты ``daily_since`` Банк России устанавливал курс этой валюты раз в месяц
(с 1-го числа), поэтому старая часть ряда — помесячные точки.
"""

from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class CbrCurrency:
    iso: str
    cbr_id: str
    nom: str            # «австралийский доллар» — именительный, со строчной
    gen: str            # «австралийского доллара» — родительный
    gen_pl_units: str   # «иен» — родительный мн. ч. для «за 100 иен»
    en: str             # «Australian dollar»
    where: str          # краткая привязка: «валюта Австралии»
    quote_units: int
    backfill_from: str
    daily_since: str
    vmin: float
    vmax: float
    country_slug: str | None = None
    aliases: tuple[str, ...] = ()

    @property
    def code(self) -> str:
        return f"{self.iso.lower()}-rub"

    @property
    def unit(self) -> str:
        if self.quote_units == 1:
            return "руб."
        return f"руб. за {self.quote_units:,}".replace(",", " ")

    @property
    def per_text(self) -> str:
        """«за одну единицу» / «за 100 иен» — для текстов."""
        if self.quote_units == 1:
            return "за одну единицу валюты"
        return f"за {self.quote_units:,} {self.gen_pl_units}".replace(",", " ")

    @property
    def name(self) -> str:
        return f"Курс {self.gen}"

    @property
    def name_en(self) -> str:
        return f"{self.en} Exchange Rate"


def _c(iso, cbr_id, nom, gen, gen_pl, en, where, q, start, daily, vmin, vmax, country=None, aliases=()):
    return CbrCurrency(iso, cbr_id, nom, gen, gen_pl, en, where, q, start, daily, vmin, vmax, country, tuple(aliases))


