def _year(iso_date: str) -> int:
    return int(iso_date[:4])


def _history_sentence(c: CbrCurrency) -> str:
    start = _year(c.backfill_from)
    daily = _year(c.daily_since)
    if daily <= start:
        return f"История ряда — с {start} года, курс устанавливается ежедневно."
    return (
        f"История ряда — с {start} года. До {daily} года Банк России устанавливал "
        "курс этой валюты раз в месяц, поэтому в старой части ряда одна точка в месяц."
    )


def _quote_sentence(c: CbrCurrency) -> str:
    if c.quote_units == 1:
        return "Курс выражается в рублях за одну единицу валюты."
    return (
        f"Банк России публикует курс {c.per_text}: на сайте ряд показан так же, "
        "чтобы не терять точность."
    )


