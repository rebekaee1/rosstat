def copy_en(c: CbrCurrency) -> dict[str, str]:
    per = "per one unit" if c.quote_units == 1 else f"per {c.quote_units:,} units"
    start = _year(c.backfill_from)
    daily = _year(c.daily_since)
    hist = (
        f"History starts in {start}."
        if daily <= start
        else f"History starts in {start}; before {daily} the Bank of Russia set this rate once a month."
    )
    return {
        "name": f"{c.en} to ruble rate",
        "description": (
            f"Official {c.en} to Russian ruble exchange rate set by the Bank of Russia, "
            f"quoted in rubles {per}."
        ),
        "methodology": (
            f"Official {c.iso}/RUB rate set by the Bank of Russia from foreign-exchange "
            f"market outcomes, in rubles {per} as in the Bank of Russia list. {hist} "
            "Averages over week, month, quarter and year are computed from the same series."
        ),
        "unit": "RUB" if c.quote_units == 1 else f"RUB per {c.quote_units:,}",
    }


def country_currency_codes() -> dict[str, tuple[str, ...]]:
    out: dict[str, tuple[str, ...]] = {}
    for c in CBR_CURRENCIES:
        if c.country_slug:
            out[c.country_slug] = out.get(c.country_slug, ()) + (c.code,)
    return out


