    if _ARREARS_NAME.search(name) and not _ARREARS_QUERY.search(raw):
        return 140
    if _LOAD_NAME.search(name) and not _LOAD_QUERY.search(raw):
        return 140
    if _STALE_NAME.search(name):
        return 60
    if _SURVEY_NAME.search(name) and not _SURVEY_QUERY.search(raw):
        return 200
    return 0
