_MAX_CODES = 14
_PRICE_LEAD = (r"(?:(?:сколько\s+(?:стоит|стоят)|почем)\s+|"
               r"(?:(?:средн\w+|текущ\w+|актуальн\w+)\s+)?"
               r"(?:цена|цены|цену|ценой|цен|стоимость|стоимости|стоимостью|тариф|тарифы|тарифа|тарифов)"
               r"(?:\s+(?:на|за|в|у|по))?\s+)")
_PRICE_TAIL = r"\s+(?:цена|цены|стоимость|тариф)\b"


def _norm(value: str) -> str:
    return " ".join(re.findall(r"[a-zа-я0-9]+", value.casefold().replace("ё", "е")))


@lru_cache(maxsize=1)
def _codes_by_pattern() -> dict[str, tuple[str, ...]]:
    out: dict[str, tuple[str, ...]] = {}
    for _aliases, pattern, _extra in _GOODS:
        rx = re.compile(pattern)
        codes = tuple(good.code for good in ALL_PRICE_GOODS if rx.search(_norm(good.label)))
        out[pattern] = codes[:_MAX_CODES]
    return out


def price_goods_concepts() -> tuple[tuple[tuple[str, ...], tuple[str, ...]], ...]:
    """Понятия поиска: псевдонимы → слова-замены и коды рядов цен (search_intent.CONCEPTS)."""
    codes = _codes_by_pattern()
    concepts = []
    for aliases, pattern, extra in _GOODS:
        # Есть общее слово в названиях — хватает его; иначе (коммуналка, мясо) перечисляем коды рядов.
        alternatives = tuple(dict.fromkeys(extra or codes.get(pattern, ())))
        if alternatives:
            concepts.append((aliases, alternatives))
    return tuple(concepts)


@lru_cache(maxsize=1)
def _alias_regex() -> re.Pattern[str]:
    aliases = sorted({_norm(alias) for group, _p, _e in _GOODS for alias in group}, key=len, reverse=True)
    return re.compile(r"(?<![a-zа-я0-9])(?:" + "|".join(re.escape(alias) for alias in aliases) + r")(?![a-zа-я0-9])")


@lru_cache(maxsize=1)
def _lead_regex() -> re.Pattern[str]:
    return re.compile(r"(?<![a-zа-я0-9])" + _PRICE_LEAD + r"$")


def prepare_price_goods(text: str) -> str:
    """«средняя цена яиц» → «яиц»: цена товара не режим «среднее» и не отдельное обязательное слово."""
    normalized = _norm(text)
    if not normalized:
        return text
    rx_alias, rx_lead = _alias_regex(), _lead_regex()
    hits = list(rx_alias.finditer(normalized))
    if not hits:
        return text
    pieces, cursor = [], 0
    for hit in hits:
        lead = rx_lead.search(normalized[cursor:hit.start()])
        start = cursor + lead.start() if lead else hit.start()
        pieces.append(normalized[cursor:start])
        pieces.append(hit.group(0))
        cursor = hit.end()
        tail = re.match(_PRICE_TAIL, normalized[cursor:])
        if tail:
            cursor += tail.end()
    pieces.append(normalized[cursor:])
    return " ".join("".join(pieces).split())


def has_price_goods(terms: tuple[tuple[str, ...], ...]) -> bool:
    return any(term in _ALTERNATIVES for term in terms)


_ALTERNATIVES = frozenset(alternatives for _aliases, alternatives in price_goods_concepts())
