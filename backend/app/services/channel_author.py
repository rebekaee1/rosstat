def channel_url(link: str, rubric: str, day: datetime | None = None) -> str:
    """Адрес страницы сайта с метками канала: по ним видно, какой пост привёл людей."""
    from app.services import site_paths
    from app.services.locale import ru_public_origin

    link = (link or "home").strip().lower()
    if link == "calendar":
        path = site_paths.calendar()
    elif link.startswith("research:") and re.fullmatch(r"[a-z0-9-]{1,80}", link[9:]):
        path = f"/research/{link[9:]}"
    elif link == "research":
        path = "/research"
    elif re.fullmatch(r"[a-z0-9-]{2,80}", link) and link != "home":
        path = site_paths.russia_indicator(link)
    else:
        path = "/"
    q = {"utm_source": "telegram", "utm_medium": "channel",
         "utm_campaign": rubric if rubric in RUBRICS else "post",
         "utm_content": (day or datetime.now(MSK)).strftime("%Y%m%d")}
    return f"{ru_public_origin()}{path}?{urlencode(q)}"


def compose_post(body_html: str, sources: list[str], link_url: str | None, link_label: str | None) -> str:
    """Текст, который уйдёт в канал: пост модели и последняя строка — источник одним словом и ссылка на график.
    Строку собирает код из оснований чисел, а не модель: так источник у каждого числа назван верно."""
    from html import escape

    tail = []
    if sources:
        tail.append(escape(", ".join(sources[:3])))
    if link_url:
        label = escape((link_label or "график и все годы").strip()[:40] or "график и все годы")
        tail.append(f'<a href="{escape(link_url, quote=True)}">{label}</a>')
    return body_html.strip() + ("\n\n" + " · ".join(tail) if tail else "")


def clean_body(text: str) -> str:
    """Текст модели → безопасный HTML Telegram; строку источника и ссылки, если модель их всё же написала, убираем."""
    from app.services.public_bot import telegram_html

    body = telegram_html(text or "")
    body = re.sub(r"<a\s[^>]*>(.*?)</a>", r"\1", body, flags=re.S | re.I)
    lines = [ln for ln in body.split("\n") if not re.match(r"^\s*(<i>)?\s*Источник\s*:", ln, re.I)]
    body = "\n".join(lines)
    return re.sub(r"\n{3,}", "\n\n", body).strip()


