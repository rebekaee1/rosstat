def plan_text(days: list, note: str) -> str:
    """План недели текстом — для записки владельцу и для контекста ежедневных запусков."""
    lines = []
    for d in days or []:
        if not isinstance(d, dict):
            continue
        posts = [p for p in (d.get("posts") or []) if isinstance(p, dict)]
        if not posts:
            lines.append(f"{d.get('day')}: без поста")
        for p in posts:
            lines.append(f"{d.get('day')}: {SIZE_TITLES.get(p.get('size'), p.get('size'))} — {p.get('about')}")
    return ("\n".join(lines) + ("\n\n" + note.strip() if note and note.strip() else "")).strip()[:3000]


