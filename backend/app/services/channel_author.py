async def _post(client, payload: dict):
    """Запрос в OpenRouter; разовые 429/5xx — один повтор."""
    resp = None
    for attempt in (0, 1):
        resp = await client.post(
            _OPENROUTER_URL, json=payload,
            headers={"Authorization": f"Bearer {settings.openrouter_api_key}", "X-Title": "Forecast Economy channel author"},
        )
        if resp.status_code in (429, 500, 502, 503, 504) and attempt == 0:
            await asyncio.sleep(3)
            continue
        break
    return resp


