_SEEN_KEY = "fe:channel:seen"


async def _last_dates(db) -> dict[str, str]:
    from sqlalchemy import func, select

    from app.models import Indicator, IndicatorData

    rows = (await db.execute(
        select(Indicator.code, func.max(IndicatorData.date)).join(IndicatorData, IndicatorData.indicator_id == Indicator.id)
        .where(Indicator.code.in_([w.code for w in WATCH])).group_by(Indicator.code))).all()
    return {code: d.isoformat() for code, d in rows if d}


async def fresh_codes(*, only_release: bool, commit: bool = True) -> list[str] | None:
    """Коды рядов с новой точкой с прошлого запуска. None — память недоступна или это первый запуск
    (тогда поводов не выдумываем: первый запуск только запоминает даты)."""
    from app.core.cache import get_state_redis
    from app.database import async_session

    try:
        async with async_session() as db:
            current = await _last_dates(db)
        r = await get_state_redis()
        raw = await r.get(_SEEN_KEY)
        seen = json.loads(raw) if raw else None
        if seen is None:
            if commit:
                await r.set(_SEEN_KEY, json.dumps(current))
            return None
        fresh = [code for code, d in current.items() if d > str(seen.get(code, ""))
                 and (not only_release or WATCH_BY_CODE[code].release)]
        if commit and fresh:
            seen.update({code: current[code] for code in fresh})
            await r.set(_SEEN_KEY, json.dumps(seen))
        return fresh
    except Exception:  # noqa: BLE001
        logger.warning("channel author: память о датах рядов недоступна", exc_info=True)
        return None


async def _budget_left() -> bool:
    from app.database import async_session

    try:
        async with async_session() as db:
            return await spent_today(db) < float(settings.channel_author_daily_usd_limit)
    except Exception:  # noqa: BLE001
        return True


async def _deliver(result: AuthorResult) -> None:
    from app.services import channel_posts
    from app.services.alerting import alert_muted

    if result.status == "http_402" and not await alert_muted("channel_author_no_credits", 24 * 3600):
        # Деньги на счёте OpenRouter кончились: автор молчит не потому, что нечего сказать. Одно сообщение в сутки.
        await channel_posts.notify_reviewers(
            "✍️ <b>Редактор канала сегодня не написал пост</b>: на счёте сервиса, через который работает модель, "
            "закончились деньги. Пополнить: openrouter.ai/settings/credits. После пополнения ничего включать не нужно.",
            kind="channel_note")
    for draft in result.drafts:
        await channel_posts.create_and_send(draft, run_id=result.run_id)
    if result.concerns and not result.drafts:
        await channel_posts.notify_reviewers(
            "✍️ <b>Редактор канала</b>: сегодня без поста.\n" + _esc(result.nothing or "") +
            "\n\n<b>Заметил в данных сайта:</b> " + _esc(result.concerns), kind="channel_note")


def _esc(s: str) -> str:
    from html import escape

    return escape(s or "")


async def channel_author_daily_job() -> dict:
    """Ежедневный запуск (после утренней сводки): автор решает, есть ли сегодня пост."""
    if not settings.channel_author_enabled:
        return {"skipped": "disabled"}
    if not await _budget_left():
        logger.warning("channel author: дневной потолок расхода исчерпан")
        return {"skipped": "budget"}
    fresh = await fresh_codes(only_release=False)
    result = await run_author("daily", fresh=fresh or None, trigger="ежедневный запуск"
                              + (": " + ", ".join(fresh) if fresh else ""))
    await _deliver(result)
    return {"decision": result.decision, "cost": round(result.cost_usd, 4)}


async def channel_author_release_job(now: datetime | None = None) -> dict:
    """Каждые полчаса с 9 до 21 по Москве: вышла новая точка важного ряда — автор пишет пост в тот же день."""
    if not settings.channel_author_enabled:
        return {"skipped": "disabled"}
    now = now or datetime.now(MSK)
    if not 9 <= now.hour < 21:
        return {"skipped": "night"}
    fresh = await fresh_codes(only_release=True)
    if not fresh:
        return {"skipped": "nothing_new"}
    if not await _budget_left():
        return {"skipped": "budget"}
    result = await run_author("release", fresh=fresh, trigger="новые точки: " + ", ".join(fresh), now=now)
    await _deliver(result)
    return {"decision": result.decision, "fresh": fresh, "cost": round(result.cost_usd, 4)}


