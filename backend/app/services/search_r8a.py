_CHEAP_QUERY = re.compile(r"дешев|недорог|подешевле|низк\w+ цен|наименьш|cheap|lowest price", re.I)


def sort_cheapest_first(raw: str, results: list[dict]) -> None:
    """«Где дешевле»: список регионов в строке идёт от меньшей цифры к большей, а не по списку регионов."""
    if not _CHEAP_QUERY.search(raw or ""):
        return
    for item in results:
        group = item.get("regional_group")
        regions = group.get("regions") if isinstance(group, dict) else None
        if regions:
            regions.sort(key=lambda entry: (entry.get("value") is None, entry.get("value") if entry.get("value") is not None else 0))


def nearest_plan(raw: str) -> tuple[str, tuple[str, ...]] | None:
    """Пояснение и понятия для ближайших рядов, если запрос про то, чего в каталоге нет."""
    text = re.sub(r"\s+", " ", (raw or "").lower().replace("ё", "е")).strip()
    for note, pattern, concepts in NEAREST_RULES:
        if pattern.search(text):
            return note, tuple(_REWRITE_TERMS.get(item, item) for item in concepts)
    return None


def nearest_query(concept: str, region_name: str | None) -> str:
    return f"{concept} {region_name}".strip() if region_name else concept


